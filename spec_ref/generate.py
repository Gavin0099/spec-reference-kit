from __future__ import annotations

from pathlib import Path
from typing import Any

from .io import SpecRefError, dump_yaml_text, file_sha256, load_yaml
from .validators import validate_canonical_table


MANIFEST_PATH = Path("exports/governed_surface_manifest.yaml")
DOC_PATH = Path("specs/generated/register-map.md")
TABLE_PATH = Path("tables/register_matrix.yaml")


def build_manifest(repo_root: Path, table: dict[str, Any]) -> dict[str, Any]:
    return {
        "schema_version": "0.1",
        "manifest_id": "spec_reference_kit_demo",
        "manifest_version": "0.1",
        "authority_surface": {
            "product": "DEMO-CHIP",
            "source_revision": "1.0",
            "state": "pilot",
        },
        "governed_tables": [
            {
                "id": table["table_id"],
                "path": TABLE_PATH.as_posix(),
                "schema": "contract/register_entry.schema.yaml",
                "state": "partial",
                "approved_entries": len(table["entries"]),
                "sha256": file_sha256(repo_root / TABLE_PATH),
            }
        ],
        "consumer_usage": {
            "allowed": [
                "register_identity_lookup",
                "bit_encoding_lookup",
                "revision_scope_lookup",
            ],
            "forbidden": [
                "infer_runtime_behavior",
                "infer_firmware_support",
                "override_customer_specific_requirement",
                "treat_engineering_note_as_normative",
            ],
        },
    }


def build_markdown(table: dict[str, Any]) -> str:
    lines = [
        "# Generated register map",
        "",
        "> Generated from `tables/register_matrix.yaml`. Do not edit this file directly.",
        "> Approval means source-aligned within the declared scope, not runtime verification.",
        "",
        "| Entry | Register | Bits | Name | Encoding | Product | Revisions | Source |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in table["entries"]:
        claim = entry["claim"]
        authority = entry["authority"]
        source = entry["source"]
        encoding = "; ".join(f"{key}={value}" for key, value in claim["encoding"].items())
        source_label = (
            f"{source['source_id']} §{source['section']} p.{source['page']} {source['table']}"
        )
        lines.append(
            "| {entry_id} | {register} | {bits} | {name} | {encoding} | {products} | {revisions} | {source} |".format(
                entry_id=entry["entry_id"],
                register=claim["register"],
                bits=claim["bit_range"],
                name=claim["name"],
                encoding=encoding,
                products=", ".join(authority["product_scope"]),
                revisions=", ".join(authority["silicon_revision_scope"]),
                source=source_label,
            )
        )
    lines.extend(
        [
            "",
            "## Explicit exclusions",
            "",
        ]
    )
    for entry in table["entries"]:
        exclusions = ", ".join(f"`{item}`" for item in entry["verification_scope"]["excludes"])
        lines.append(f"- `{entry['entry_id']}`: {exclusions}")
    lines.append("")
    return "\n".join(lines)


def expected_outputs(repo_root: Path) -> dict[Path, str]:
    table = load_yaml(repo_root / TABLE_PATH)
    errors = validate_canonical_table(table)
    if errors:
        raise SpecRefError("canonical table invalid:\n- " + "\n- ".join(errors))
    return {
        MANIFEST_PATH: dump_yaml_text(build_manifest(repo_root, table)),
        DOC_PATH: build_markdown(table),
    }


def generate_outputs(repo_root: Path, check: bool = False) -> list[str]:
    mismatches: list[str] = []
    for relative, expected in expected_outputs(repo_root).items():
        target = repo_root / relative
        if check:
            actual = target.read_text(encoding="utf-8") if target.exists() else None
            if actual != expected:
                mismatches.append(relative.as_posix())
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(expected)
    return mismatches

